def seed_master_catalogue(dry_run: bool = False) -> Dict[str, Any]:
    """
    Executes expansion across all categories and upserts authentic records into Supabase.
    """
    from engine.app.database.supabase_client import db_client

    catalog = get_master_opportunity_catalogue()
    logger.info(f"Loaded {len(catalog)} master opportunity records from catalogue.")

    stats = {
        "total_catalogued": len(catalog),
        "upserted": 0,
        "failed": 0,
        "categories": {},
        "statuses": {},
    }

    for item in catalog:
        cat = item.get("category", "General")
        stat = item.get("application_status", "open")
        stats["categories"][cat] = stats["categories"].get(cat, 0) + 1
        stats["statuses"][stat] = stats["statuses"].get(stat, 0) + 1

        if dry_run or not db_client.is_connected:
            stats["upserted"] += 1
            continue

        try:
            exam_id = db_client.upsert_examination(item)
            if exam_id:
                stats["upserted"] += 1
                
                # Also upsert validated important dates
                if item.get("application_open_date") or item.get("application_close_date") or item.get("examination_date"):
                    db_client.upsert_examination_dates(exam_id, {
                        "notification_date": item.get("notification_date"),
                        "application_opening_date": item.get("application_open_date"),
                        "application_closing_date": item.get("application_close_date"),
                        "correction_window_start": item.get("correction_start_date"),
                        "correction_window_end": item.get("correction_end_date"),
                        "admit_card_release_date": item.get("admit_card_date"),
                        "examination_start_date": item.get("examination_date"),
                        "examination_end_date": item.get("exam_end_date"),
                        "result_date": item.get("result_date"),
                    })

                # Also upsert eligibility rules
                db_client.upsert_eligibility_rules(exam_id, {
                    "min_age": item.get("minimum_age") or 18,
                    "max_age": item.get("maximum_age") or 35,
                    "eligible_streams": item.get("required_disciplines") or ["All Disciplines"],
                    "educational_qualifications": item.get("educational_eligibility") or ["Refer official notification."],
                })
            else:
                stats["failed"] += 1
        except Exception as e:
            logger.error(f"Failed to upsert {item.get('title')}: {e}")
            stats["failed"] += 1

    logger.info(f"Master catalogue seed completed: {stats['upserted']} upserted, {stats['failed']} failed.")
    return stats

